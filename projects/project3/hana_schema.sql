-- SAP HANA schema for Inventory Management & Stock Optimization
-- Uses column tables and types suitable for HANA

CREATE COLUMN TABLE PRODUCTS (
  PRODUCT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SKU NVARCHAR(64) NOT NULL UNIQUE,
  NAME NVARCHAR(256) NOT NULL,
  CATEGORY NVARCHAR(128),
  UNIT NVARCHAR(32),
  REORDER_LEVEL DECIMAL(18,4),
  LEAD_TIME_DAYS INT,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE COLUMN TABLE SUPPLIERS (
  SUPPLIER_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME NVARCHAR(256) NOT NULL,
  CONTACT_EMAIL NVARCHAR(256),
  PHONE NVARCHAR(64),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE COLUMN TABLE LOCATIONS (
  LOCATION_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE NVARCHAR(64) NOT NULL UNIQUE,
  NAME NVARCHAR(256) NOT NULL,
  TYPE NVARCHAR(64),
  ADDRESS NVARCHAR(512),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE COLUMN TABLE INVENTORY (
  INVENTORY_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PRODUCT_ID BIGINT NOT NULL,
  LOCATION_ID BIGINT NOT NULL,
  QUANTITY DECIMAL(18,4) DEFAULT 0,
  RESERVED DECIMAL(18,4) DEFAULT 0,
  LAST_UPDATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (PRODUCT_ID, LOCATION_ID)
);

CREATE COLUMN TABLE SHIPMENTS (
  SHIPMENT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SHIPMENT_REF NVARCHAR(128) UNIQUE,
  SUPPLIER_ID BIGINT,
  ORIGIN_LOCATION_ID BIGINT,
  DEST_LOCATION_ID BIGINT,
  EXPECTED_AT TIMESTAMP,
  ARRIVED_AT TIMESTAMP,
  STATUS NVARCHAR(64),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE COLUMN TABLE ORDERS (
  ORDER_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ORDER_REF NVARCHAR(128) UNIQUE,
  ORDER_TYPE NVARCHAR(64),
  LOCATION_ID BIGINT,
  PLACED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FULFILLED_AT TIMESTAMP,
  STATUS NVARCHAR(64)
);

CREATE COLUMN TABLE ORDER_ITEMS (
  ORDER_ITEM_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ORDER_ID BIGINT,
  PRODUCT_ID BIGINT,
  QUANTITY DECIMAL(18,4),
  UNIT_PRICE DECIMAL(18,4),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE COLUMN TABLE INVENTORY_MOVEMENTS (
  MOVEMENT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PRODUCT_ID BIGINT NOT NULL,
  FROM_LOCATION_ID BIGINT,
  TO_LOCATION_ID BIGINT,
  QUANTITY DECIMAL(18,4) NOT NULL,
  MOVEMENT_TYPE NVARCHAR(128),
  REF_ID BIGINT,
  OCCURRED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Useful indexes
CREATE INDEX IDX_INV_PRODUCT ON INVENTORY(PRODUCT_ID);
CREATE INDEX IDX_INV_LOCATION ON INVENTORY(LOCATION_ID);
CREATE INDEX IDX_MOV_PRODUCT ON INVENTORY_MOVEMENTS(PRODUCT_ID);
